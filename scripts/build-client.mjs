import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const read = path => readFileSync(new URL(path, root), 'utf8').replaceAll('\r\n', '\n');
const modules = {
  'conversation-cards': 'const { CardTail, LiveCards, commandError } = createConversationCards({ React, h, tf, commandText, commandCode, useFormValue });',
  'project-cards': 'const { PROJECT_COMMAND_NAME, runProjectCommand, ProjectView, ProjectChatProposals } = createProjectCards({ React, h, tf, commandError, commandCode, stripCode, projectionValue, openTab: openConversationTab });',
  'task-brief': 'const { BRIEF_COMMAND_NAME, runBriefCommand, BriefTail, BriefPanelSection } = createTaskBrief({ React, h, tf, commandError, projectionValue, useFormValue });',
  styles: '',
};

let source = read('src/client/index.js');
for (const [name, connect] of Object.entries(modules)) {
  const marker = `  // @client ${name}\n`;
  if (!source.includes(marker)) throw new Error(`Missing client source marker: ${name}`);
  const module = read(`src/client/${name}.js`).replace(/^export /mu, '').trimEnd();
  const code = name === 'styles' ? module : module.split('\n').map(line => line ? `  ${line}` : '').join('\n');
  source = source.replace(marker, () => [code, connect ? `  ${connect}` : ''].filter(Boolean).join('\n') + '\n');
}
const bundle = '// Generated by npm run build:client from src/client.\n' + source;
if (process.argv.includes('--check')) {
  if (read('lib/client.js') !== bundle) throw new Error('Client bundle is stale. Run npm run build:client.');
} else writeFileSync(new URL('lib/client.js', root), bundle);
